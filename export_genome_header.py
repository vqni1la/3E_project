"""Export saved_models/best_genome.json as an ESP32 C++ header.

Default paths assume this file lives in C:\\3E_project and the ESP32 sketch
is stored in C:\\3E_project\\rc_car_ai_esp32\\.

Usage:
    python export_genome_header.py
    python export_genome_header.py --input saved_models/best_genome.json --output rc_car_ai_esp32/best_genome_weights.h
"""

from __future__ import annotations

import argparse
import json
import math
import os
import tempfile
from pathlib import Path
from typing import Any

INPUT_COUNT = 5
HIDDEN_COUNT = 8
OUTPUT_COUNT = 2
EXPECTED_WEIGHT_COUNT = (
    INPUT_COUNT * HIDDEN_COUNT
    + HIDDEN_COUNT
    + HIDDEN_COUNT * OUTPUT_COUNT
    + OUTPUT_COUNT
)  # 66 values: W1, b1, W2, b2

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_INPUT = SCRIPT_DIR / "saved_models" / "best_genome.json"
DEFAULT_OUTPUT = SCRIPT_DIR / "rc_car_ai_esp32" / "best_genome_weights.h"


def _cpp_float(value: float) -> str:
    """Format a finite number as a C++ float literal."""
    if not math.isfinite(value):
        raise ValueError(f"Non-finite weight value: {value!r}")
    text = format(value, ".10g")
    # Ensure integer-looking values are valid and explicit float literals.
    if "." not in text and "e" not in text.lower():
        text += ".0"
    return text + "f"


def generate_header(input_json: Path | str, output_header: Path | str) -> Path:
    """Read a best_genome.json file and atomically write the C++ header."""
    input_path = Path(input_json).expanduser().resolve()
    output_path = Path(output_header).expanduser().resolve()

    if not input_path.is_file():
        raise FileNotFoundError(
            f"Model JSON was not found: {input_path}\n"
            "Run car_simulator.py until best_genome.json is created, or pass --input."
        )

    try:
        model: dict[str, Any] = json.loads(input_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON in {input_path}: {exc}") from exc

    if not isinstance(model, dict):
        raise ValueError("The JSON root must be an object.")

    raw_weights = model.get("weights")
    if not isinstance(raw_weights, list):
        raise ValueError("The JSON must contain a 'weights' array.")
    if len(raw_weights) != EXPECTED_WEIGHT_COUNT:
        raise ValueError(
            f"Expected {EXPECTED_WEIGHT_COUNT} weights for a "
            f"{INPUT_COUNT}-{HIDDEN_COUNT}-{OUTPUT_COUNT} network, "
            f"but found {len(raw_weights)}. No header was written."
        )

    weights: list[float] = []
    for index, raw in enumerate(raw_weights):
        if isinstance(raw, bool) or not isinstance(raw, (int, float)):
            raise ValueError(f"Weight #{index} is not a number: {raw!r}")
        value = float(raw)
        if not math.isfinite(value):
            raise ValueError(f"Weight #{index} is not finite: {raw!r}")
        weights.append(value)

    generation_raw = model.get("generation", -1)
    fitness_raw = model.get("fitness", float("nan"))
    try:
        generation = int(generation_raw)
        fitness = float(fitness_raw)
    except (TypeError, ValueError) as exc:
        raise ValueError("'generation' must be an integer and 'fitness' a number.") from exc
    if not math.isfinite(fitness):
        raise ValueError("'fitness' must be a finite number.")

    formatted_weights = []
    for start in range(0, len(weights), 4):
        line = ", ".join(_cpp_float(v) for v in weights[start:start + 4])
        formatted_weights.append(f"    {line},")

    content = f"""#pragma once

// Automatically generated by export_genome_header.py.
// Source: {input_path.name}
// Weight order must match ai/neural_network.py:
// W1(5x8), b1(8), W2(8x2), b2(2).
// Model generation: {generation}, fitness: {fitness:.12g}

constexpr int AI_INPUTS = {INPUT_COUNT};
constexpr int AI_HIDDEN = {HIDDEN_COUNT};
constexpr int AI_OUTPUTS = {OUTPUT_COUNT};
constexpr int AI_WEIGHT_COUNT = {EXPECTED_WEIGHT_COUNT};
constexpr int AI_MODEL_GENERATION = {generation};
constexpr float AI_MODEL_FITNESS = {_cpp_float(fitness)};

static const float BEST_GENOME_WEIGHTS[AI_WEIGHT_COUNT] = {{
{os.linesep.join(formatted_weights)}
}};
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replacement avoids leaving a partially written header if interrupted.
    fd, temporary_name = tempfile.mkstemp(
        prefix=output_path.name + ".", suffix=".tmp", dir=str(output_path.parent)
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as file:
            file.write(content)
        os.replace(temporary_name, output_path)
    except Exception:
        try:
            os.unlink(temporary_name)
        except OSError:
            pass
        raise

    return output_path


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate best_genome_weights.h from best_genome.json."
    )
    parser.add_argument(
        "--input", default=str(DEFAULT_INPUT),
        help=f"Path to best_genome.json (default: {DEFAULT_INPUT})",
    )
    parser.add_argument(
        "--output", default=str(DEFAULT_OUTPUT),
        help=f"Output header path (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args()

    try:
        output = generate_header(args.input, args.output)
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}")
        return 1

    model = json.loads(Path(args.input).expanduser().resolve().read_text(encoding="utf-8"))
    print("ESP32 header generated successfully.")
    print(f"Generation : {model.get('generation', 'unknown')}")
    print(f"Fitness    : {model.get('fitness', 'unknown')}")
    print(f"Weights    : {EXPECTED_WEIGHT_COUNT}")
    print(f"Output     : {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
